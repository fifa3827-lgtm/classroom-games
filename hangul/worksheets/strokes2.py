def svg(ch, show_numbers=True, light=False):
    col = "#D8D2C6" if light else "#2b2b2b"
    parts = ['<svg viewBox="0 0 100 100" width="100%" height="100%">']
    for d, _s, _e in J[ch]:
        parts.append(f'<path d="{d}" fill="none" stroke="{col}" stroke-width="9" '
                     f'stroke-linecap="round" stroke-linejoin="round"/>')
    if show_numbers:
        for i, (_d, start, end) in enumerate(J[ch], 1):
            parts.append(arrow(end[0], end[1], end[2], end[3]))
            parts.append(num(i, start[0], start[1]))
    parts.append('</svg>')
    return "".join(parts)

