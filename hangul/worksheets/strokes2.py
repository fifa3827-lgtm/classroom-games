import math

def arrow(x, y, dx, dy, c="#C0453A"):
    a = math.atan2(dy, dx); s = 7
    p2 = (x - s*math.cos(a-0.45), y - s*math.sin(a-0.45))
    p3 = (x - s*math.cos(a+0.45), y - s*math.sin(a+0.45))
    return (f'<polygon points="{x:.1f},{y:.1f} {p2[0]:.1f},{p2[1]:.1f} '
            f'{p3[0]:.1f},{p3[1]:.1f}" fill="{c}"/>')

def num(n, x, y):
    return (f'<circle cx="{x}" cy="{y}" r="8.5" fill="#C0453A"/>'
            f'<text x="{x}" y="{y+3.4}" font-size="11" fill="#fff" '
            f'text-anchor="middle" font-weight="700">{n}</text>')

